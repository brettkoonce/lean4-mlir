#!/usr/bin/env python3
"""Generate PLATFORMS.md and the book's platforms table from scripts/platform/support.tsv.

PLATFORMS.md is the support matrix (every cell as markdown), then every platform-suite run from
runs/platform/*/manifest.json + results.tsv, newest first. blueprint/src/figures/platforms.tex is
the same matrix as a LaTeX tabular for Appendix A's Table "platforms": platform, the pinned plugin,
then one cell per rung holding the date and the short tag of the record (the link dropped), and
the runbooks as a line under the table. One row per platform, one column per rung of the ladder
(suite, mnist, cifar, imagenette, imagenet); a `suite` cell of `auto:<host>` is filled from the
newest suite run with that host, `auto:<host>/<backend>` from the newest with that backend too.
scripts/platform/check.sh calls this after each run; `--check` fails if either committed file is
stale.
"""
import csv, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / 'runs' / 'platform'
SUPPORT = ROOT / 'scripts' / 'platform' / 'support.tsv'
OUT = ROOT / 'PLATFORMS.md'
TEX = ROOT / 'blueprint' / 'src' / 'figures' / 'platforms.tex'

HEAD = """# Platforms

Which GPU platforms run which build of this repo, and how far up the ladder each has been
taken; the second lowerer, IREE, is a row of the same table. Generated by
`scripts/platform/platforms_md.py` from `scripts/platform/support.tsv` and `runs/platform/*/`
— do not hand-edit; the book's platforms table (Appendix A) is generated from the same rows.
One profile, `scripts/platform/env.sh`, says what each platform runs with (backend, plugin,
device variable, a Jetson's allocator defaults); the platforms' pages are in `deploy/`.

## Support matrix

A cell is the last run of that rung on that platform — its date and where the record lives.
`-` means not run there, which is not a failure; `n/a` means the rung cannot run there. The
ladder is `scripts/platform/check.sh` (tiers 0–2, minutes), then `lake run mnist` (a minute),
`cifar` (~6 min), `imagenette` (~6 h; `imagenette-orin` on the Jetson, a day) and `imagenet`
(four cards, weeks); the proofs rung before them is platform-free and has no column.

| platform | env.sh profile | plugin | runbook | suite | mnist | cifar | imagenette | imagenet |
|---|---|---|---|---|---|---|---|---|
"""

SUITE_HEAD = """
## Platform-suite runs

`scripts/platform/check.sh` (`--plan` shows what it runs); the design is
[`planning/platform_integration.md`](planning/platform_integration.md). A run is green when
every test matches the platform's baseline in `scripts/platform/expected/`. When a run turns
red, diff its `manifest.json` against the last green run on the same box: core equal and
platform changed points at the driver or plugin; platform equal and core changed points at
this repo.

| date | host | GPUs | driver | runtime | plugin | PJRT API | repo | tiers | pass | xfail | fail | skip | |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
"""


def counts(d):
    """(manifest, status counts, verdict) of one suite run."""
    m = json.loads((d / 'manifest.json').read_text())
    with open(d / 'results.tsv') as f:
        res = [r for r in csv.DictReader(f, delimiter='\t') if not r['test'].startswith('build:')
               or r['status'] != 'PASS']
    n = {s: sum(r['status'] == s for r in res) for s in ('PASS', 'XFAIL', 'FAIL', 'XPASS', 'SKIP')}
    verdict = '✅' if n['FAIL'] == 0 and n['XPASS'] == 0 else ('⚠ xpass' if n['FAIL'] == 0 else '❌')
    return m, n, verdict


def row(d):
    m, n, verdict = counts(d)
    c, p = m['core'], m['platform']
    names = sorted({g['name'] for g in p['gpus']}) or [p.get('platform_name') or '?']
    gpus = f"{len(p['gpus']) or p['gpu_count_visible']}× " + ' / '.join(
        x.replace('NVIDIA GeForce ', '') for x in names)
    rt = p.get('runtime') or {}
    runtime = ', '.join(f'{k} {v}' for k, v in rt.items() if k in ('runtime', 'dnn')) or p.get('platform_version') or ''
    plugin = p.get('plugin_package') or Path(p.get('plugin_path') or '?').name
    api = f"{p.get('pjrt_api_plugin')} (hdr {c.get('pjrt_api_header')})"
    repo = c['repo_sha'][:8] + ('+dirty' if c.get('repo_dirty') else '')
    link = f"[{verdict}](runs/platform/{d.name}/results.tsv)"
    return (m['date'], f"| {m['date'][:10]} | {p['host']} | {gpus} | {p.get('driver') or ''} | {runtime} "
            f"| {plugin} | {api} | `{repo}` | 0–{c['tier']} | {n['PASS']} | {n['XFAIL']} "
            f"| {n['FAIL']} | {n['SKIP']} | {link} |")


def suite_dirs():
    return [d for d in RUNS.iterdir()
            if (d / 'manifest.json').exists() and (d / 'results.tsv').exists()] if RUNS.exists() else []


def suite_cell(spec):
    """The newest suite run on `spec` — `host`, or `host/backend` for a box with two platforms
    (minerva: the B50 and the 7900 XTX): date, verdict, pass count, link — or `-`."""
    host, _, backend = spec.partition('/')
    best = None
    for d in suite_dirs():
        m, n, verdict = counts(d)
        if m['platform']['host'] != host or (backend and m['platform'].get('backend') != backend):
            continue
        if best is None or m['date'] > best[0]:
            best = (m['date'], f"{m['date'][:10]} · {verdict} {n['PASS']} pass, tiers 0–{m['core']['tier']} "
                               f"([results](runs/platform/{d.name}/results.tsv))")
    return best[1] if best else '-'


def rows():
    """support.tsv's rows, the `auto:` suite cells filled: [[platform, env, plugin, runbook, suite, mnist, cifar, imagenette, imagenet]]."""
    out = []
    with open(SUPPORT) as f:
        for ln in f:
            if not ln.strip() or ln.startswith('#'):
                continue
            cells = ln.rstrip('\n').split('\t')
            if len(cells) != 9:
                sys.exit(f'support.tsv: {len(cells)} fields, expected 9: {ln[:60]}')
            if cells[4].startswith('auto:'):
                cells[4] = suite_cell(cells[4][5:])
            out.append(cells)
    return out


def matrix(rows):
    return ''.join('| ' + ' | '.join(r) + ' |\n' for r in rows)


# ── the book's table ─────────────────────────────────────────────────────────

LINK = re.compile(r'\[([^\]]*)\]\([^)]*\)')
TAG = re.compile(r'\(([^()]*)\)')   # the first parenthetical of the WHERE part, links stripped
TEX_HEAD = """% Generated by scripts/platform/platforms_md.py from scripts/platform/support.tsv — do not
% hand-edit; `platforms_md.py --check` fails when this file is stale. Appendix A's platforms
% table \\input{}s it. Each rung cell is the record's tag, what has run on that rung on that
% platform; the date and the link live in PLATFORMS.md. The platform's details and its
% runbook are the lines under the table, keyed by the name before the dash in support.tsv.
\\setlength{\\tabcolsep}{3pt}
\\footnotesize
\\begin{tabular}{@{}p{0.10\\textwidth}p{0.22\\textwidth}p{0.12\\textwidth}p{0.12\\textwidth}p{0.12\\textwidth}p{0.12\\textwidth}p{0.12\\textwidth}@{}}
\\textbf{Platform} & \\textbf{Plugin, pinned} & \\textbf{suite} & \\textbf{mnist} & \\textbf{cifar} & \\textbf{imagenette} & \\textbf{imagenet} \\\\[2pt]
\\hline \\\\[-6pt]
"""


def tex(s):
    """Markdown cell text as LaTeX: links to their text, `code` to \\texttt, specials escaped."""
    s = LINK.sub(r'\1', s)
    parts = s.split('`')
    out = []
    for i, part in enumerate(parts):
        part = (part.replace('\\', '\\textbackslash{}').replace('&', '\\&').replace('%', '\\%')
                .replace('$', '\\$').replace('#', '\\#').replace('_', '\\_').replace('{', '\\{')
                .replace('}', '\\}').replace('~', '\\textasciitilde{}').replace('^', '\\textasciicircum{}'))
        part = (part.replace('—', '---').replace('–', '--').replace('→', '--').replace('×', '$\\times$')
                .replace('§', '\\S').replace('✅', 'pass').replace('½', '$\\tfrac12$'))
        out.append('\\texttt{' + part.replace('/', '/\\allowbreak ') + '}' if i % 2 else part)
    return ''.join(out)


def tex_rung(cell):
    """A rung cell as the book shows it: `--`, `n/a`, or the record's tag (what ran); a suite cell
    filled from a manifest shows its tiers and pass count."""
    if cell == '-':
        return '--'
    if cell.startswith('n/a'):
        return 'n/a'
    m = re.search(r'(\d+) pass, tiers (\S+)', cell)
    if m:
        return f'tiers {m.group(2)}, {m.group(1)} pass'
    m = TAG.search(LINK.sub(r'\1', cell.partition(' · ')[2]))
    return tex(m.group(1)) if m else '?' 


def platform(cell):
    """(name, details) of a platform cell: the text before the first ' — ' and the rest."""
    name, _, details = cell.partition(' — ')
    return name, details


def tex_matrix(rows):
    body = ''
    for i, r in enumerate(rows):
        cells = [tex(platform(r[0])[0]), tex(r[2])] + [tex_rung(c) for c in r[4:]]
        body += ' & '.join('\\cellleft ' + c for c in cells) + (' \\\\[4pt]\n' if i + 1 < len(rows) else ' \\\\\n')
    key = ''
    for r in rows:
        name, details = platform(r[0])
        runbook = r[3].split(' (')[0].split(';')[0]
        key += '\\textbf{' + tex(name) + '}\\quad ' + tex(details).rstrip('.') + '; runbook ' + tex(runbook) + '.\\\\\n'
    return (TEX_HEAD + body + '\\end{tabular}\n'
            '\\par\\smallskip{\\footnotesize\\raggedright\n' + key + '\\par}\n')


def render():
    rs = rows()
    suite = sorted((row(d) for d in suite_dirs()), reverse=True)
    return HEAD + matrix(rs) + SUITE_HEAD + ''.join(r + '\n' for _, r in suite), tex_matrix(rs)


def main():
    md, tx = render()
    if '--check' in sys.argv:
        for path, text in ((OUT, md), (TEX, tx)):
            if not path.exists() or path.read_text() != text:
                sys.exit(f'{path.relative_to(ROOT)} is stale — run scripts/platform/platforms_md.py')
        print('✓ PLATFORMS.md and blueprint/src/figures/platforms.tex match support.tsv + runs/platform/')
        return
    OUT.write_text(md)
    TEX.write_text(tx)


if __name__ == '__main__':
    main()
